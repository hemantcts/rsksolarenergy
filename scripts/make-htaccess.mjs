// Generates public/.htaccess: 301s from the old WordPress site (CLAUDE.md §5) plus security
// headers (CLAUDE.md §9). Product redirects are derived from products.json so they can never
// drift from the actual slugs. Run with `npm run htaccess` after product slugs change.
import { writeFileSync } from 'node:fs';
import products from '../src/data/products.json' with { type: 'json' };

const oldSiteProducts = products.filter((p) => p.oldSlug); // only products that existed on the old WordPress site
const productRedirects = oldSiteProducts.map((p) => `Redirect 301 /product/${p.oldSlug}/ /products/${p.slug}/`).join('\n');

const out = `# Generated by scripts/make-htaccess.mjs — do not hand-edit the redirect blocks.
# Regenerate with \`npm run htaccess\` after changing src/data/products.json.

# ---------------------------------------------------------------------------
# Redirects from the old WordPress site (CLAUDE.md §5).
# ---------------------------------------------------------------------------

# Products from the old site — ${oldSiteProducts.length}, old slug (including the 6 lorem-ipsum ones) to the real one.
${productRedirects}
Redirect 301 /shop/ /products/

# Services -> the pages that actually replaced them.
Redirect 301 /service/hydropower-plants/ /hybrid-solar-systems/
Redirect 301 /service/battery-material/ /solar-panels/
Redirect 301 /service/solar-panel-service/ /off-grid-solar-systems/
Redirect 301 /services/ /

# Core pages.
Redirect 301 /about-us/ /about/
Redirect 301 /thank-you/ /

# Demo "projects" (lorem-ipsum content, two of them wind energy — RSK does not do wind).
# No real installations page exists yet (see TODO-content.md); send to About until it does.
Redirect 301 /project/plant-installation/ /about/
Redirect 301 /project/plant-installation-2/ /about/
Redirect 301 /project/solar-installation/ /about/
Redirect 301 /project/solar-installation-2/ /about/
Redirect 301 /project/wind-energy-plant/ /about/
Redirect 301 /project/wind-energy-plant-2/ /about/
Redirect 301 /projects/ /about/

# City page renamed: Rupnagar is searched as Ropar (2026-09-15).
Redirect 301 /solar-company-rupnagar/ /solar-company-ropar/

# Old blog posts. One 2023 sizing post is replaced by a real equivalent; the rest were generic
# filler (see TODO-content.md) and just go to the guides index.
Redirect 301 /how-to-size-your-home-solar-system-in-2023/ /blog/how-to-size-home-solar-punjab/
Redirect 301 /the-solar-revolution-why-its-time-to-make-the-switch/ /blog/
Redirect 301 /beyond-the-grid-is-your-solar-energy-is-ready-for-the-future-india/ /blog/
Redirect 301 /hybrid-solar-systems-with-battery-backup-innovative-and-sustainable-solution-rsk-solar-energy/ /hybrid-solar-systems/

# Everything else on the old install (wp-admin, wp-content, wp-json, feeds, category/tag
# archives, pagination) is deliberately NOT redirected — it 404s cleanly. The old install was
# compromised (CLAUDE.md §5); there is no reason to keep acknowledging WordPress paths.

# ---------------------------------------------------------------------------
# Security headers (CLAUDE.md §9).
# ---------------------------------------------------------------------------
# The real Content-Security-Policy (script-src/style-src with per-build hashes, default-src,
# img-src, etc.) is delivered as a <meta> tag by Astro itself — see the security.csp block in
# astro.config.mjs — because those hashes have to match whatever a given build actually inlined.
# frame-ancestors is the one CSP directive <meta> cannot deliver, so it is set here instead, as
# its OWN policy with no other directives in it. Do not merge this into a fuller policy: a
# header-delivered script-src/default-src here would apply IN ADDITION to the meta tag's (a
# resource must satisfy every policy in force), and without the meta tag's hashes it would block
# the site's own scripts.
<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=()"
  Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains; preload"
  Header always set Content-Security-Policy "frame-ancestors 'none'"
</IfModule>

# HTTPS + www→apex (adjust if RSK prefers www), then trailing-slash canonicalisation.
# Astro is built with trailingSlash: 'always' (every page emits as a directory with its own
# index.html — see astro.config.mjs), so the canonical URL for every page ends in "/". This
# adds the slash for anyone who requests a page without one, /asda included, whether or not
# that path actually exists — a real page 301s to itself+/, a typo still 301s to itself+/ and
# then hits the normal 404 there. Real files (anything with an extension: .css, .js, .png,
# .xml, .txt, .ico, .woff2, ...) are left alone, so assets and robots.txt/sitemap.xml are
# never touched. QSA preserves any query string across the redirect.
<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteCond %{HTTPS} off
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
  RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]
  RewriteRule ^ https://%1%{REQUEST_URI} [L,R=301]
  RewriteCond %{REQUEST_URI} !/$
  RewriteCond %{REQUEST_URI} !\\.[a-zA-Z0-9]+$
  RewriteRule ^(.*)$ $1/ [R=301,L,QSA]
</IfModule>

# site.webmanifest has no built-in Apache MIME mapping on most hosts, so it falls back to
# text/plain and (per a live PageSpeed check) gets served with no cache header at all — flagged
# under "Use efficient cache lifetimes". Declare it explicitly so the ExpiresByType rule below
# actually applies to it.
<IfModule mod_mime.c>
  AddType application/manifest+json .webmanifest
</IfModule>

# Static asset caching. HTML is left to Astro's own headers / short cache so content updates
# show up promptly; fonts and images are content-hashed so they can cache for a year.
<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType font/woff2 "access plus 1 year"
  ExpiresByType image/webp "access plus 1 year"
  ExpiresByType image/png "access plus 1 month"
  ExpiresByType image/x-icon "access plus 1 year"
  ExpiresByType image/svg+xml "access plus 1 month"
  ExpiresByType text/css "access plus 1 month"
  ExpiresByType application/javascript "access plus 1 month"
  ExpiresByType application/manifest+json "access plus 1 month"
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml
</IfModule>

# Astro special-cases the 404 route: it emits 404.html, NOT 404/index.html, even though every
# other page is built as a directory (trailingSlash: 'always'). Pointing this at /404/ makes the
# error document itself a miss, which re-enters the error handler — LiteSpeed gives up and serves
# Hostinger's default 404 instead of ours. Must stay a real file path.
ErrorDocument 404 /404.html
`;

writeFileSync(new URL('../public/.htaccess', import.meta.url), out);
const redirectCount = products.filter((p) => p.oldSlug).length;
console.log(`.htaccess written: ${redirectCount} product redirects (of ${products.length} products) + core redirects + security headers`);
